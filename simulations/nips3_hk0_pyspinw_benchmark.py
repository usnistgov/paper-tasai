"""
One-plane HK0 NiPS3 pyspinw benchmark.

This script answers a narrower, more realistic TAS question than the earlier
GK channel demo:

    If we stay in a single HK0 scattering plane, how much of the NiPS3-like
    Hamiltonian family can we discriminate without any LLM layer?

The benchmark uses a pyspinw-backed model built from the NiPS3 structure and a
provisional bond-shell mapping. It treats the measured observables as magnon
mode energies at selected Q points in the HK0 plane. That is still lighter than
full TAS intensity fitting, but it is materially stronger than the earlier
analytic surrogate because the spectra are generated by the same spin-wave
backend used elsewhere in the project.
"""

